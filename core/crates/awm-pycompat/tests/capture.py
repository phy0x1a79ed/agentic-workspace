from pathlib import Path

assert sys.version_info[:2] == (3, 12), f"capture with the awm env's Python 3.12, not {sys.version}"

ROOT = Path(__file__).resolve().parent.parent
FIX = ROOT / "tests" / "fixtures"
RNG = random.Random(20261106)
MAX_CP = 0x10FFFF


def write(name: str, data) -> None:
    (FIX / name).write_text(json.dumps(data, ensure_ascii=True, indent=1) + "\n")


# ---------------------------------------------------------------- character tables

def ranges(pred) -> list[tuple[int, int]]:
    out, start = [], None
    for cp in range(MAX_CP + 2):
        hit = cp <= MAX_CP and not 0xD800 <= cp <= 0xDFFF and pred(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


WORD = re.compile(r"\w")
TABLES = {
    "WORD": lambda c: WORD.match(c) is not None,
    "SPACE": str.isspace,
    "DIGIT": str.isdigit,
    "DECIMAL": str.isdecimal,
    "PRINTABLE": str.isprintable,
    # Final-sigma context, probed through lower(): a char that ends the scan as cased, and one the scan skips.
    "SIGMA_CASED": lambda c: (c + "\u03a3").lower()[-1] == "\u03c2",
    "SIGMA_SKIP": lambda c: ("A" + c + "\u03a3").lower()[-1] == "\u03c2" and ("A\u03a3" + c).lower()[1] == "\u03c2",
}


def lower_map() -> list[tuple[int, str]]:
    return [(cp, chr(cp).lower()) for cp in range(MAX_CP + 1)
            if not 0xD800 <= cp <= 0xDFFF and chr(cp).lower() != chr(cp)]


def rust_str(s: str) -> str:
    return '"' + "".join(f"\\u{{{ord(c):x}}}" for c in s) + '"'


def write_tables() -> dict:
    lines = [
        "// Generated by tests/capture.py from Python "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.",
        "",
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
    ]
    counts = {}
    for name, pred in TABLES.items():
        rs = ranges(pred)
        counts[name] = len(rs)
        body = ", ".join(f"(0x{a:x}, 0x{b:x})" for a, b in rs)
        lines += ["", f"pub static {name}: &[(u32, u32)] = &[{body}];"]
    lm = lower_map()
    counts["LOWER"] = len(lm)
    body = ", ".join(f"(0x{cp:x}, {rust_str(lo)})" for cp, lo in lm)
    lines += ["", f"pub static LOWER: &[(u32, &str)] = &[{body}];", ""]
    (ROOT / "src" / "tables.rs").write_text("\n".join(lines))
    return counts


