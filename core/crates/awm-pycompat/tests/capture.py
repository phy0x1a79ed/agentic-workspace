def json_values() -> list:
    vals = [
        None, True, False, 0, -1, 2**53 + 1, -(2**63), 2**64 - 1, 0.0, -0.0, 1.0, 0.1, 1e-7, 1e16, 1e22, 123456789.125,
        5e-324, 1.7976931348623157e308, 100.0, 1e15, 1.5e-5, "", "plain", 'quote " and \\ backslash', "tab\tnl\n",
        "\x00\x1f\x7f", "\u00e9", "\u65e5\u672c", "\U0001f44d\U0001f3fd", "\u2028\u2029", "\ufffd",
        [], {}, [1, "a", None, [2, {"k": "v"}]], {"b": 1, "a": 2, "c": {"z": [], "y": {}}}, {"\u00e9": "\u00fc", "1": 1, "": None},
    ]
    for _ in range(60):
        vals.append(random_value(3))
    return vals


def random_value(depth: int):
    kind = RNG.choice(["int", "float", "str", "bool", "none", "list", "dict"] if depth else ["int", "float", "str"])
    if kind == "int":
        return RNG.choice([RNG.randint(-10, 10), RNG.randint(-2**62, 2**62)])
    if kind == "float":
        return RNG.choice([RNG.random(), RNG.uniform(-1e20, 1e20), RNG.random() * 10 ** RNG.randint(-30, 30), float(RNG.randint(0, 99))])
    if kind == "str":
        return RNG.choice(PIECES + SEPARATORS + ["k", "key", "x y", "'", '"', "'\""])
    if kind == "bool":
        return RNG.random() < 0.5
    if kind == "none":
        return None
    if kind == "list":
        return [random_value(depth - 1) for _ in range(RNG.randint(0, 4))]
    return {RNG.choice(["a", "b", "z", "\u00e9", "key", "2", "x y"]) + str(i): random_value(depth - 1) for i in range(RNG.randint(0, 4))}


def json_cases() -> list[dict]:
    out = []
    for v in json_values():
        out.append({
            "input": json.dumps(v, ensure_ascii=False, separators=(",", ":")),
            "dumps": json.dumps(v),
            "sort_keys": json.dumps(v, sort_keys=True),
            "indent1": json.dumps(v, indent=1),
            "unicode": json.dumps(v, ensure_ascii=False),
        })
    return out


def tag(v):
    """Encode a Python value as JSON a test can rebuild: tuples, dicts, big ints and non-finite floats are tagged."""
    if isinstance(v, tuple):
        return {"$tuple": [tag(x) for x in v]}
    if isinstance(v, list):
        return [tag(x) for x in v]
    if isinstance(v, dict):
        return {"$dict": [[tag(k), tag(x)] for k, x in v.items()]}
    if isinstance(v, float) and (v != v or v in (float("inf"), float("-inf"))):
        return {"$float": repr(v)}
    if isinstance(v, int) and not isinstance(v, bool) and not -(2**63) <= v < 2**63:
        return {"$int": str(v)}
    return v


def repr_cases() -> list[dict]:
    vals = json_values() + [float("nan"), float("inf"), float("-inf"), (), (1,), (1, "a"), ("x", (2, 3.5)),
                            "it's", 'say "hi"', "both ' and \"", "\\", "\x07\x08\x1b", "\x80\x9f\xa0\xad",
                            "\u200b\u200e\u2028\ufeff\ufffe", "\U000e0001",
                            {1: "int key", "s": (1, 2)}, [(), [()]], 10**20, -(10**20)]
    vals += corpus()[:120]
    return [{"value": tag(v), "repr": repr(v)} for v in vals]


# ---------------------------------------------------------------- difflib

SURNAMES = ["Huttenhower", "Huttenhauer", "Hutenhower", "Smith", "Smyth", "Schmidt", "Garcia", "Garc\u00eda", "Nguyen",
            "Ng", "O'Brien", "OBrien", "M\u00fcller", "Mueller", "Li", "Lee", "Zhang", "Chang", "Wang", "Kowalski",
            "Kowalsky", "aaaaab", "abababab", "", "x"]


def lines_text(n: int, vocab: list[str]) -> str:
    return "".join(RNG.choice(vocab) + RNG.choice(["\n", "\n", "\n", "\r\n"]) for _ in range(n))


def difflib_cases() -> dict:
    ratio = []
    for a in SURNAMES:
        for b in SURNAMES:
            ratio.append({"a": a.lower(), "b": b.lower(), "ratio": repr(difflib.SequenceMatcher(None, a.lower(), b.lower()).ratio())})
    for _ in range(80):
        a = "".join(RNG.choice("abcde") for _ in range(RNG.randint(0, 300)))
        b = "".join(RNG.choice("abcde") for _ in range(RNG.randint(0, 300)))
        sm = difflib.SequenceMatcher(None, a, b)
        ratio.append({"a": a, "b": b, "ratio": repr(sm.ratio()), "opcodes": sm.get_opcodes()})

    vocab = ["alpha", "beta", "gamma", "", "- item", "# Heading", "same line", "\u65e5\u672c\u8a9e", "x" * 90]
    diff = []
    for i in range(80):
        n = RNG.choice([0, 1, 3, 10, 40, 250])
        old = lines_text(n, vocab) + RNG.choice(["", "no newline at end"])
        new_lines = old.splitlines(keepends=True)
        for _ in range(RNG.randint(0, 6)):
            op = RNG.choice(["ins", "del", "rep"])
            at = RNG.randint(0, len(new_lines))
            if op == "ins" or not new_lines:
                new_lines.insert(at, RNG.choice(vocab) + "\n")
            elif op == "del":
                new_lines.pop(min(at, len(new_lines) - 1))
            else:
                new_lines[min(at, len(new_lines) - 1)] = RNG.choice(vocab) + "\n"
        new = "".join(new_lines)
        if i % 7 == 0:
            new = new.replace("\n", "\u2028", 1)
        a, b = f"p{i:04x}@{i}", f"p{i:04x}@{i + 1}"
        diff.append({"old": old, "new": new, "fromfile": a, "tofile": b,
                     "diff": "".join(difflib.unified_diff(old.splitlines(keepends=True), new.splitlines(keepends=True),
                                                          fromfile=a, tofile=b))})
    return {"ratio": ratio, "unified_diff": diff}


def main() -> None:
    FIX.mkdir(parents=True, exist_ok=True)
    counts = write_tables()
    write("strings.json", string_cases())
    write("datetime.json", datetime_cases())
    write("json.json", json_cases())
    write("repr.json", repr_cases())
    write("difflib.json", difflib_cases())
    write("meta.json", {"python": sys.version.split()[0], "unicode": unicodedata.unidata_version, "tables": counts})
    print(json.dumps(counts))


if __name__ == "__main__":
    main()
