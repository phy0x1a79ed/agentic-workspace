def corpus() -> list[str]:
    out = list(PIECES)
    out += [f"a{s}b{s}" for s in SEPARATORS + SPACES]
    out += [f"{s}lead and trail{s}" for s in SEPARATORS + SPACES]
    out += ["", " ", "\n", "\n\n", "line\n", "line\r\n", "a\r\rb", "trail\r", "x\n\ny\n"]
    pool = PIECES + SEPARATORS + SPACES + [". ", "! ", "? ", ".\n", "?!", "  "]
    for _ in range(300):
        out.append("".join(RNG.choice(pool) for _ in range(RNG.randint(1, 8))))
    return out


SENTENCE_END = re.compile(r"(?<=[.!?])\s+|\n")
TOKENS = re.compile(r"\w+|[^\w\s]")
WORDS = re.compile(r"\w+")
NONWORDS = re.compile(r"\W+")


def ascii_fold(s: str) -> str:
    return unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()


def string_cases() -> list[dict]:
    cases = []
    for s in corpus():
        cases.append({
            "s": s,
            "len": len(s),
            "split": s.split(),
            "strip": s.strip(),
            "lstrip": s.lstrip(),
            "rstrip": s.rstrip(),
            "splitlines": s.splitlines(),
            "splitlines_keepends": s.splitlines(keepends=True),
            "lower": s.lower(),
            "norm": " ".join(s.split()).lower(),
            "isdigit": s.isdigit(),
            "head200": s[:200],
            "head3": s[:3],
            "tokens": TOKENS.findall(s),
            "words_lower": WORDS.findall(s.lower()),
            "nonword_squash": NONWORDS.sub(" ", s.lower()).strip(),
            "sentences": [p for p in SENTENCE_END.split(s) if p and p.strip()],
            "ascii_fold": ascii_fold(s),
        })
    return cases


# ---------------------------------------------------------------- datetimes

EPOCH = datetime(1970, 1, 1, tzinfo=timezone.utc)


def ms_to_iso(ms: int) -> str:
    return datetime.fromtimestamp(int(ms) / 1000, tz=timezone.utc).isoformat()


def iso_to_ms(s: str):
    s = s.strip()
    if not s:
        return None
    try:
        dt = datetime.fromisoformat(s.replace("Z", "+00:00"))
    except ValueError:
        return None
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return int(dt.timestamp() * 1000)


