def datetime_cases() -> dict:
    ms_values = [0, 1, 999, 1000, 1001, -1, -999, -1000, -1001, 1730000000000, 1730000000123, 1762407096018,
                 253402300799999, -62135596800000]
    ms_values += [RNG.randint(0, 2_000_000_000_000) for _ in range(400)]
    ms_values += [RNG.randint(-62135596800000, 253402300799999) for _ in range(100)]
    ms_iso = [{"ms": ms, "iso": ms_to_iso(ms)} for ms in ms_values]

    parse = []
    for s in ISO_INPUTS:
        case = {"s": s, "iso_to_ms": iso_to_ms(s)}
        try:
            dt = datetime.fromisoformat(s)
            case["fromisoformat"] = dt.isoformat()
        except ValueError:
            case["fromisoformat"] = None
        parse.append(case)

    aware = []
    for _ in range(200):
        us = RNG.randint(-62135596800000000, 2**53 - 1)  # float timestamps are exact only below 2**53 us
        dt = EPOCH + timedelta(microseconds=us)
        if RNG.random() < 0.3:
            dt = dt.replace(microsecond=0)
        aware.append({"us": us - us % 1_000_000 if not dt.microsecond else us, "iso": dt.isoformat(),
                      "zulu": dt.strftime("%Y-%m-%dT%H:%M:%SZ"), "date": dt.date().isoformat(),
                      "ms": int(dt.timestamp() * 1000)})
    ms_date = [{"ms": ms, "date": datetime.fromtimestamp(ms / 1000, timezone.utc).date().isoformat()}
               for ms in ms_values]
    return {"ms_to_iso": ms_iso, "parse": parse, "aware": aware, "ms_date": ms_date}


