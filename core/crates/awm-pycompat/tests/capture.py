"""Capture the Python 3.12 behaviour awm-pycompat reproduces, as fixtures and generated tables.

Run from the crate root: ~/miniforge3/bin/mamba run -n awm python tests/capture.py
Writes tests/fixtures/*.json and src/tables.rs. Every input is synthetic.
"""

from __future__ import annotations

